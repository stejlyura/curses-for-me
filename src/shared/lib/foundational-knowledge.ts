export function getAllGlossaryItems(courseSlug?: string): GlossaryItem[] {
  const items: GlossaryItem[] = [];

  Object.entries(moduleFoundationalData).forEach(([modIdStr, explainer]) => {
    const modId = parseInt(modIdStr, 10);
    let resolvedCourse = 'senior-marketing';
    if (modId >= 7 && modId <= 11) resolvedCourse = 'media-buying';
    else if (modId >= 12 && modId <= 16) resolvedCourse = 'affiliate-manager';
    else if (modId >= 17 && modId <= 21) resolvedCourse = 'lead-generation';

    if (!courseSlug || courseSlug === resolvedCourse) {
      explainer.glossary.forEach((g) => {
        items.push({
          term: g.term,
          courseSlug: resolvedCourse,
          simpleDefinition: g.definition,
          whyItMatters: explainer.whyItMatters,
          realWorldAnalogy: explainer.realWorldAnalogy,
          example: explainer.mindsetShift.seniorView,
        });
      });
    }
  });

  // Deduplicate by term
  const seen = new Set<string>();
  return items.filter((item) => {
    if (seen.has(item.term)) return false;
    seen.add(item.term);
    return true;
  });
}
